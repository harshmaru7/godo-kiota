// formatGo runs gofmt on src, returning the original (for debuggability) if it
// does not parse.
func formatGo(src string) string {
	out, err := format.Source([]byte(src))
	if err != nil {
		fmt.Fprintln(os.Stderr, "inferencegen: gofmt failed (emitting unformatted):", err)
		return src
	}
	return string(out)
}

